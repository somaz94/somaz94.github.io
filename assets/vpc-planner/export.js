/* assets/vpc-planner/export.js
 * Serialises a plan as Terraform, YAML or CSV.
 *
 * Pure by design: no DOM, no storage, no network. Takes a plan, returns a
 * string. ui.js decides which one to show and puts it on the page.
 *
 * Hand-maintained. Nothing generates this file.
 *
 * Constraints held here:
 *   - The output is meant to be pasted into a real repository, so it has to be
 *     valid on its own: the Terraform block declares the `aws_subnet` resources
 *     with an explicit `cidr_block`, not a `cidrsubnet()` expression that would
 *     recompute the split and be free to disagree with the table above it.
 *   - The plan knows an AZ letter, not a region, so `availability_zone` indexes
 *     a declared `aws_availability_zones` data source rather than hardcoding a
 *     region the user never chose.
 *   - Names become Terraform resource identifiers, so they are sanitised to
 *     `[A-Za-z0-9_-]` with a leading letter. A name prefix of "10-app" must not
 *     produce `resource "aws_subnet" "10-app_a1" {`.
 *   - CSV quotes any field containing a comma, a quote or a newline, and doubles
 *     embedded quotes. The AZ and name columns are user-supplied text.
 *   - YAML is plain block style. `10.0.0.0/16` would survive unquoted but a name
 *     like `no`, `y` or `on` would not, so every user-supplied scalar is quoted.
 *   - Nothing here writes a file or triggers a download. The page shows the text
 *     and offers Copy; a download would be the only place this tool touches the
 *     filesystem, and it does not need to.
 */
(function (global) {
  'use strict';

  var CIDR = global.VPCidr;

  /* Terraform identifiers admit letters, digits, underscores and dashes, and
   * may not start with a digit. Anything else collapses to an underscore. */
  function ident(name) {
    var s = String(name).replace(/[^A-Za-z0-9_-]/g, '_');
    if (!/^[A-Za-z]/.test(s)) { s = 's_' + s; }
    return s;
  }

  /* Double-quoted YAML/Terraform scalar: only backslash and the quote itself
   * need escaping, and no user field here can contain a newline. */
  function quote(value) {
    return '"' + String(value).replace(/\\/g, '\\\\').replace(/"/g, '\\"') + '"';
  }

  function csvCell(value) {
    var s = String(value);
    if (/[",\n\r]/.test(s)) { return '"' + s.replace(/"/g, '""') + '"'; }
    return s;
  }

  /* aws_vpc + one aws_subnet per allocated block. */
  function terraform(plan) {
    var azCount = plan.subnets.reduce(function (max, s) {
      return s.azIndex + 1 > max ? s.azIndex + 1 : max;
    }, 0);

    var out = [
      '# Generated by https://somaz.blog/vpc-planner/ — review before applying.',
      '',
      'data "aws_availability_zones" "available" {',
      '  state = "available"',
      '}',
      '',
      'resource "aws_vpc" "main" {',
      '  cidr_block = ' + quote(CIDR.format(plan.parent)),
      '}'
    ];

    plan.subnets.forEach(function (s) {
      out.push('');
      out.push('resource "aws_subnet" ' + quote(ident(s.name)) + ' {');
      out.push('  vpc_id            = aws_vpc.main.id');
      out.push('  cidr_block        = ' + quote(CIDR.format(s.block)));
      out.push('  availability_zone = data.aws_availability_zones.available.names[' + s.azIndex + ']');
      out.push('');
      out.push('  tags = {');
      out.push('    Name = ' + quote(s.name));
      out.push('  }');
      out.push('}');
    });

    if (azCount > 0) {
      out.push('');
      out.push('# Needs at least ' + azCount + ' availability zone' +
        (azCount === 1 ? '' : 's') + ' in the target region.');
    }
    return out.join('\n') + '\n';
  }

  /* A flat mapping the user can drop into their own values file. */
  function yaml(plan) {
    var out = [
      '# Generated by https://somaz.blog/vpc-planner/',
      'vpc_cidr: ' + quote(CIDR.format(plan.parent)),
      'subnets:'
    ];

    plan.subnets.forEach(function (s) {
      out.push('  - name: ' + quote(s.name));
      out.push('    cidr: ' + quote(CIDR.format(s.block)));
      out.push('    az: ' + quote(s.az));
      out.push('    first: ' + quote(s.first));
      out.push('    last: ' + quote(s.last));
      out.push('    usable: ' + s.usable);
    });

    if (plan.gaps.length) {
      out.push('unallocated:');
      plan.gaps.forEach(function (g) {
        out.push('  - ' + quote(CIDR.format(g.block)));
      });
    }
    return out.join('\n') + '\n';
  }

  /* name,cidr,az,first,last,usable */
  function csv(plan) {
    var rows = [['name', 'cidr', 'az', 'first', 'last', 'usable'].join(',')];
    plan.subnets.forEach(function (s) {
      rows.push([
        csvCell(s.name),
        csvCell(CIDR.format(s.block)),
        csvCell(s.az),
        csvCell(s.first),
        csvCell(s.last),
        csvCell(s.usable)
      ].join(','));
    });
    return rows.join('\n') + '\n';
  }

  /* Single entry point so ui.js does not carry a switch over format names. */
  function render(plan, format) {
    if (!plan || !plan.subnets.length) { return ''; }
    if (format === 'yaml') { return yaml(plan); }
    if (format === 'csv') { return csv(plan); }
    return terraform(plan);
  }

  global.VPExport = {
    terraform: terraform,
    yaml: yaml,
    csv: csv,
    render: render
  };
})(this);
