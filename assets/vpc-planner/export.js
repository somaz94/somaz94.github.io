/* assets/vpc-planner/export.js — a plan as Terraform, YAML or CSV.
 * Pure: no DOM, no storage, no network. Plan in, string out; no download.
 *
 *   - Terraform uses explicit `cidr_block`s, never `cidrsubnet()`, which would
 *     recompute the split and could disagree with the table.
 *   - The plan knows an AZ letter, not a region, so `availability_zone` indexes
 *     an `aws_availability_zones` data source.
 *   - YAML quotes every scalar: a name like `no` or `on` would not survive bare.
 */
(function (global) {
  'use strict';

  var CIDR = global.VPCidr;

  /* Terraform identifier: `[A-Za-z0-9_-]` with a leading letter, so "10-app"
   * never yields `"10-app_a1"`. */
  function ident(name) {
    var s = String(name).replace(/[^A-Za-z0-9_-]/g, '_');
    if (!/^[A-Za-z]/.test(s)) { s = 's_' + s; }
    return s;
  }

  /* Only backslash and quote need escaping; no exported field holds a newline. */
  function quote(value) {
    return '"' + String(value).replace(/\\/g, '\\\\').replace(/"/g, '\\"') + '"';
  }

  function csvCell(value) {
    var s = String(value);
    if (/[",\n\r]/.test(s)) { return '"' + s.replace(/"/g, '""') + '"'; }
    return s;
  }

  function terraform(plan) {
    var azCount = plan.subnets.reduce(function (max, s) {
      return s.azIndex + 1 > max ? s.azIndex + 1 : max;
    }, 0);

    var out = [
      '# Generated by https://somaz.blog/vpc-planner/ — review before applying.',
      '',
      'data "aws_availability_zones" "available" {',
      '  state = "available"',
      '}',
      '',
      'resource "aws_vpc" "main" {',
      '  cidr_block = ' + quote(CIDR.format(plan.parent)),
      '}'
    ];

    plan.subnets.forEach(function (s) {
      out.push('');
      out.push('resource "aws_subnet" ' + quote(ident(s.name)) + ' {');
      out.push('  vpc_id            = aws_vpc.main.id');
      out.push('  cidr_block        = ' + quote(CIDR.format(s.block)));
      out.push('  availability_zone = data.aws_availability_zones.available.names[' + s.azIndex + ']');
      out.push('');
      out.push('  tags = {');
      out.push('    Name = ' + quote(s.name));
      out.push('  }');
      out.push('}');
    });

    if (azCount > 0) {
      out.push('');
      out.push('# Needs at least ' + azCount + ' availability zone' +
        (azCount === 1 ? '' : 's') + ' in the target region.');
    }
    return out.join('\n') + '\n';
  }

  function yaml(plan) {
    var out = [
      '# Generated by https://somaz.blog/vpc-planner/',
      'vpc_cidr: ' + quote(CIDR.format(plan.parent)),
      'subnets:'
    ];

    plan.subnets.forEach(function (s) {
      out.push('  - name: ' + quote(s.name));
      out.push('    cidr: ' + quote(CIDR.format(s.block)));
      out.push('    az: ' + quote(s.az));
      out.push('    first: ' + quote(s.first));
      out.push('    last: ' + quote(s.last));
      out.push('    usable: ' + s.usable);
    });

    if (plan.gaps.length) {
      out.push('unallocated:');
      plan.gaps.forEach(function (g) {
        out.push('  - ' + quote(CIDR.format(g.block)));
      });
    }
    return out.join('\n') + '\n';
  }

  function csv(plan) {
    var rows = [['name', 'cidr', 'az', 'first', 'last', 'usable'].join(',')];
    plan.subnets.forEach(function (s) {
      rows.push([
        csvCell(s.name),
        csvCell(CIDR.format(s.block)),
        csvCell(s.az),
        csvCell(s.first),
        csvCell(s.last),
        csvCell(s.usable)
      ].join(','));
    });
    return rows.join('\n') + '\n';
  }

  function render(plan, format) {
    if (!plan || !plan.subnets.length) { return ''; }
    if (format === 'yaml') { return yaml(plan); }
    if (format === 'csv') { return csv(plan); }
    return terraform(plan);
  }

  global.VPExport = {
    terraform: terraform,
    yaml: yaml,
    csv: csv,
    render: render
  };
})(this);
